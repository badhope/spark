#!/usr/bin/env python
"""Fail CI when a change adds a D/E/F function or grows an existing one.

The baseline is explicit rather than "run radon and eyeball the output": every
legacy complex function is listed with its current complexity, so a new hotspot
cannot hide in a 59-line report. When a function is intentionally refactored,
regenerate the baseline with ``--write-baseline`` and review the diff.

Radon ranks: A 1-5, B 6-10, C 11-20, D 21-30, E 31-40, F 41+.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from radon.complexity import cc_visit

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "spark"
BASELINE_PATH = ROOT / "scripts" / "complexity-baseline.json"
MIN_COMPLEXITY = 21
GROWTH_ALLOWANCE = 3


def _collect_functions() -> dict[str, int]:
    """Map ``relative/path.py:qualname`` to complexity for every D/E/F function."""
    functions: dict[str, int] = {}
    for path in sorted(SRC.rglob("*.py")):
        relative = path.relative_to(ROOT).as_posix()
        try:
            blocks = cc_visit(path.read_text(encoding="utf-8"))
        except (OSError, SyntaxError) as exc:
            print(f"cannot parse {relative}: {exc}", file=sys.stderr)
            raise SystemExit(2) from exc
        # radon yields both a Class block and standalone Function blocks for
        # methods; dedupe by (name, lineno) so each method is counted once.
        method_lines = {
            (method.name, method.lineno)
            for block in blocks
            for method in (getattr(block, "methods", None) or [])
        }
        for block in blocks:
            methods = getattr(block, "methods", None)
            if methods:
                if block.complexity >= MIN_COMPLEXITY:
                    key = f"{relative}:{block.name}"
                    functions[key] = max(functions.get(key, 0), block.complexity)
                for method in methods:
                    if method.complexity >= MIN_COMPLEXITY:
                        key = f"{relative}:{block.name}.{method.name}"
                        functions[key] = max(functions.get(key, 0), method.complexity)
                continue
            if hasattr(block, "methods"):
                continue
            if (block.name, block.lineno) in method_lines:
                continue
            if block.complexity >= MIN_COMPLEXITY:
                key = f"{relative}:{block.name}"
                functions[key] = max(functions.get(key, 0), block.complexity)
    return functions


def _write_baseline(functions: dict[str, int]) -> None:
    payload = {
        "comment": "Generated by scripts/check_complexity.py --write-baseline; review the diff.",
        "threshold": MIN_COMPLEXITY,
        "functions": dict(sorted(functions.items())),
    }
    BASELINE_PATH.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"wrote {len(functions)} functions to {BASELINE_PATH.relative_to(ROOT)}")


def _load_baseline() -> dict[str, int]:
    try:
        payload = json.loads(BASELINE_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"cannot read baseline {BASELINE_PATH}: {exc}", file=sys.stderr)
        raise SystemExit(2) from exc
    functions = payload.get("functions")
    if not isinstance(functions, dict):
        print("baseline has no functions object", file=sys.stderr)
        raise SystemExit(2)
    return {str(key): int(value) for key, value in functions.items()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write-baseline",
        action="store_true",
        help="rewrite the baseline from the current tree",
    )
    args = parser.parse_args()
    current = _collect_functions()
    if args.write_baseline:
        _write_baseline(current)
        return 0

    baseline = _load_baseline()
    new = sorted(set(current) - set(baseline))
    grown = sorted(
        (key, baseline[key], complexity)
        for key, complexity in current.items()
        if key in baseline and complexity > baseline[key] + GROWTH_ALLOWANCE
    )
    if new or grown:
        if new:
            print("New D/E/F functions (split them or add to the reviewed baseline):")
            for key in new:
                print(f"  + {key} = {current[key]}")
        if grown:
            print("Existing functions grew by more than "
                  f"{GROWTH_ALLOWANCE} points:")
            for key, before, after in grown:
                print(f"  ! {key}: {before} -> {after}")
        return 1
    print(
        f"complexity gate passed: {len(current)} known D/E/F functions, "
        "no new hotspots"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
